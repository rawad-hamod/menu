export function translateError(locale: Locale, message: string): string {
  if (locale === 'en') return message

  for (const [englishPrefix, key] of Object.entries(errorKeys)) {
    if (message === englishPrefix) return translate(locale, key)
    if (message.startsWith(`${englishPrefix}: `)) {
      return `${translate(locale, key)}: ${message.slice(englishPrefix.length + 2)}`
    }
  }

  return message
}
